//development server that provides a fast and optimized experience,
//especially during development.

// Why Vite is used in React?
// Here’s what makes Vite great for React projects:

// 🔥 1. Lightning Fast Development Server
// Uses native ES Modules (ESM) in the browser.
// No bundling needed during development – changes reflect almost instantly.

// ⚡️ 2. Fast Hot Module Replacement (HMR)
// React component changes update in the browser without full reload.
// Much faster than Webpack-based setups.

// 📦 3. Optimized Production Build
// Uses Rollup under the hood for bundling.
// Produces smaller and more efficient production code.

// 🧠 4. Simplified Configuration
// Less boilerplate than Webpack or Create React App (CRA).
// Supports JSX, TypeScript, CSS modules, and more out of the box.

//Summary:
// Dev speed: Vite is super fast, while Webpack/CRA can be slower in large projects.
// HMR (Hot Module Replacement.): Vite offers fast and reliable hot module replacement; Webpack/CRA can be slower.
// Config: Vite requires minimal configuration, whereas Webpack/CRA is often complex.
// Build Tool: Vite uses Rollup for production builds, while Webpack/CRA uses Webpack.

